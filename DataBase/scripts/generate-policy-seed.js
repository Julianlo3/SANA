#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const POLICIES_DIR = path.join(__dirname, '..', 'policies');
const INIT_SCRIPTS_DIR = path.join(__dirname, '..', 'init-scripts');
const DOLLAR_TAG = '$md$';

const RELEASES = [
  {
    folder: 'v1',
    output: '06-legal-v1-texts.sql',
    versions: {
      privacy_policy: '1.0',
      terms_of_use: '1.0',
      data_treatment: '2.0',
      dependent_consent: '2.0',
      account_terms: '1.0',
      donation_terms: '1.0',
      schedule_terms: '2.0',
      clinical_note_terms: '2.0',
    },
  },
];

const byName = (a, b) => a.localeCompare(b);

function readPolicyTexts(folder) {
  const dir = path.join(POLICIES_DIR, folder);
  return Object.fromEntries(
    fs
      .readdirSync(dir)
      .filter((file) => file.endsWith('.md'))
      .sort(byName)
      .map((file) => [
        path.basename(file, '.md'),
        fs.readFileSync(path.join(dir, file), 'utf8').replaceAll('\r\n', '\n').trim(),
      ]),
  );
}

function validate(release, texts) {
  const expected = Object.keys(release.versions).sort(byName);
  const found = Object.keys(texts).sort(byName);
  const missing = expected.filter((type) => !found.includes(type));
  const unexpected = found.filter((type) => !expected.includes(type));
  if (missing.length || unexpected.length) {
    throw new Error(
      `${release.folder}: missing [${missing.join(', ')}], unexpected [${unexpected.join(', ')}]`,
    );
  }
  for (const [type, text] of Object.entries(texts)) {
    if (!text) throw new Error(`${release.folder}/${type}.md is empty`);
    if (text.includes(DOLLAR_TAG)) {
      throw new Error(`${release.folder}/${type}.md contains the reserved tag ${DOLLAR_TAG}`);
    }
    if (type.length > 30) throw new Error(`pd_type too long: ${type}`);
  }
}

function buildInsert(type, version, text) {
  return [
    'INSERT INTO public.policy_documents (pd_type, pd_version, pd_content)',
    `VALUES ('${type}', '${version}', ${DOLLAR_TAG}${text}${DOLLAR_TAG})`,
    'ON CONFLICT (pd_type, pd_version) DO NOTHING;',
  ].join('\n');
}

function buildScript(release, texts) {
  const header = [
    '-- Generated by DataBase/scripts/generate-policy-seed.js. Do not edit by hand.',
    `-- Source: DataBase/policies/${release.folder}/*.md`,
  ].join('\n');
  const inserts = Object.keys(release.versions).map((type) =>
    buildInsert(type, release.versions[type], texts[type]),
  );
  return `${header}\n\n${inserts.join('\n\n')}\n`;
}

function main() {
  for (const release of RELEASES) {
    const texts = readPolicyTexts(release.folder);
    validate(release, texts);
    const target = path.join(INIT_SCRIPTS_DIR, release.output);
    fs.writeFileSync(target, buildScript(release, texts), 'utf8');
    console.log(`Generated ${path.relative(process.cwd(), target)}`);
  }
}

main();
