-- Paquetes de atención posteriores a una valoración psicológica realizada.
CREATE TABLE IF NOT EXISTS public.care_packages (
  cp_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cp_patient_person_id integer NULL REFERENCES public.person(per_id),
  cp_patient_dependent_id integer NULL REFERENCES public.dependents(dep_id),
  cp_assessment_app_id integer NOT NULL REFERENCES public.appointments(app_id),
  psy_id integer NOT NULL REFERENCES public.psychologist(psy_id),
  sec_id integer NOT NULL REFERENCES public.person(per_id),
  cp_session_limit integer NOT NULL CHECK (cp_session_limit > 0),
  cp_priority varchar(10) NOT NULL CHECK (cp_priority IN ('alta', 'media', 'baja')),
  cp_state varchar(12) NOT NULL DEFAULT 'activo' CHECK (cp_state IN ('activo', 'finalizado', 'cancelado')),
  cp_created_at timestamptz NOT NULL DEFAULT now(),
  cp_closed_at timestamptz NULL,
  cp_closed_by integer NULL REFERENCES public.person(per_id),
  cp_close_reason text NULL,
  CONSTRAINT care_package_patient_ck CHECK (
    (cp_patient_person_id IS NOT NULL AND cp_patient_dependent_id IS NULL)
    OR (cp_patient_person_id IS NULL AND cp_patient_dependent_id IS NOT NULL)
  )
);

ALTER TABLE public.appointments
  ADD COLUMN IF NOT EXISTS cp_id integer NULL REFERENCES public.care_packages(cp_id),
  ADD COLUMN IF NOT EXISTS app_kind varchar(12) NOT NULL DEFAULT 'valoracion';

ALTER TABLE public.appointments
  DROP CONSTRAINT IF EXISTS "Appointment_state_ck";
ALTER TABLE public.appointments
  ADD CONSTRAINT "Appointment_state_ck"
  CHECK (app_state IN ('pendiente', 'asignada', 'confirmada', 'descartada', 'cancelada', 'realizada', 'no_asistio'));
ALTER TABLE public.appointments
  ADD CONSTRAINT appointment_kind_ck CHECK (app_kind IN ('valoracion', 'paquete'));

CREATE UNIQUE INDEX IF NOT EXISTS care_package_active_person_uq
  ON public.care_packages(cp_patient_person_id) WHERE cp_state = 'activo';
CREATE UNIQUE INDEX IF NOT EXISTS care_package_active_dependent_uq
  ON public.care_packages(cp_patient_dependent_id) WHERE cp_state = 'activo';
CREATE INDEX IF NOT EXISTS appointment_care_package_idx ON public.appointments(cp_id);
