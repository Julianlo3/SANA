import type {
  AppointmentMode,
  AppointmentState,
} from "../types/appointment-types";

/** Formats appointment dates in Colombia time, independent of browser timezone. */
const TIME_ZONE = "America/Bogota";

/**
 * Defines the date format.
 */
const DATE_FORMAT = new Intl.DateTimeFormat("es-CO", {
  timeZone: TIME_ZONE,
  day: "numeric",
  month: "short",
  year: "numeric",
});

/**
 * Defines the date time format.
 */
const DATE_TIME_FORMAT = new Intl.DateTimeFormat("es-CO", {
  timeZone: TIME_ZONE,
  weekday: "short",
  day: "numeric",
  month: "short",
  hour: "numeric",
  minute: "2-digit",
});

/** Formats a date as YYYY-MM-DD for date fields. */
const DAY_KEY_FORMAT = new Intl.DateTimeFormat("en-CA", {
  timeZone: TIME_ZONE,
});

/**
 * Formats a timezone-aware timestamp, such as a request creation date.
 * @param iso iso input.
 * @returns Result of the operation.
 */
export function formatDate(iso: string): string {
  return DATE_FORMAT.format(new Date(iso));
}

/**
 * Formats an appointment date and time.
 * @param iso iso input.
 * @returns Result of the operation.
 */
export function formatDateTime(iso: string): string {
  return DATE_TIME_FORMAT.format(new Date(iso));
}

/**
 * Formats a date-only value, such as a birth date, without timezone conversion.
 * @param date Date value.
 * @returns Result of the operation.
 */
export function formatCalendarDate(date: string): string {
  const [year, month, day] = date.slice(0, 10).split("-").map(Number);

  return new Intl.DateTimeFormat("es-CO", {
    timeZone: "UTC",
    day: "numeric",
    month: "long",
    year: "numeric",
  }).format(new Date(Date.UTC(year, month - 1, day)));
}

/**
 * Returns the YYYY-MM-DD calendar date for an instant in Colombia time.
 * @param iso iso input.
 * @returns Result of the operation.
 */
export function toColombiaDay(iso: string): string {
  return DAY_KEY_FORMAT.format(new Date(iso));
}

/**
 * Returns today's date in Colombia as YYYY-MM-DD.
 * @returns Result of the operation.
 */
export function colombiaToday(): string {
  return DAY_KEY_FORMAT.format(new Date());
}

/**
 * Las horas llegan como "08:00" o "08:00:00"; se muestran sin segundos.
 * @param time Time value.
 * @returns Result of the operation.
 */
export function formatSlotTime(time: string): string {
  return time.slice(0, 5);
}

/**
 * Defines appointment state labels.
 */
export const APPOINTMENT_STATE_LABELS: Record<AppointmentState, string> = {
  pendiente: "Pendiente",
  asignada: "Asignada",
  confirmada: "Confirmada",
  descartada: "Descartada",
  cancelada: "Cancelada",
  realizada: "Realizada",
};

/**
 * Defines appointment mode labels.
 */
export const APPOINTMENT_MODE_LABELS: Record<AppointmentMode, string> = {
  presencial: "Presencial",
  virtual: "Virtual",
};

/**
 * Defines the gender labels.
 */
const GENDER_LABELS: Record<string, string> = {
  F: "Femenino",
  M: "Masculino",
  O: "Otro",
  P: "Prefiere no decir",
};

/**
 * Maps the backend's single-letter gender code to its display label.
 * @param code code input.
 * @returns Result of the operation.
 */
export function formatGender(code: string | null): string {
  if (!code) return "No indicado";
  return GENDER_LABELS[code] ?? code;
}

/**
 * Detects placeholder email addresses generated by the backend when no
 * address was supplied; these values are not real contact addresses.
 * @param email email input.
 * @returns Result of the operation.
 */
export function isPlaceholderEmail(email: string | null): boolean {
  return email !== null && /^doc_\d+@sana\.org$/i.test(email);
}